"""Core data model.

Design invariant (brief §3.1): variants of a task are never generated by running
different harnesses. One base trajectory is authored *semantically*, and each arm
is a deterministic render of that same semantic object under a factor setting.
Held constant by construction: system prompt, tool schemas, user task text, turn
count, tool-call count, and the semantic content of every tool return.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Any, Literal


# --------------------------------------------------------------------------
# Identifiers are references, not literals, so F4 can be varied orthogonally
# to F1 without touching authored content.
# --------------------------------------------------------------------------

IdKind = Literal["user", "order", "sku", "ticket", "account", "session", "request", "txn"]


@dataclass(frozen=True)
class IdRef:
    """A placeholder for an identifier, realized per-arm by the F4 setting."""

    kind: IdKind
    index: int

    def key(self) -> str:
        return f"{self.kind}:{self.index}"


# --------------------------------------------------------------------------
# Tools
# --------------------------------------------------------------------------


@dataclass
class ToolParam:
    name: str
    type: str
    description: str


@dataclass
class ToolSchema:
    """Held constant across every arm of a task (§3.1): name, description, and
    argument order are never touched by any factor."""

    name: str
    description: str
    params: list[ToolParam] = field(default_factory=list)

    def canonical_field_order(self) -> list[str]:
        return [p.name for p in self.params]


# --------------------------------------------------------------------------
# Semantic tool returns
# --------------------------------------------------------------------------


class FieldRole(str, Enum):
    """Why a field exists. Factor renderers key off role, not name."""

    TASK_RELEVANT = "task_relevant"   # required to complete the task; never dropped
    CONTEXTUAL = "contextual"         # plausible but not needed for the task
    METADATA = "metadata"             # nested envelope / provenance material


@dataclass
class SemanticField:
    name: str
    value: Any                 # may embed IdRef instances
    role: FieldRole
    schema_order: int          # canonical position, used by the F1 eval-like arm


@dataclass
class SemanticReturn:
    """The invariant content of one tool return.

    Only TASK_RELEVANT fields carry task semantics. F1 varies which of the other
    roles are rendered and in what order; it never adds or removes a
    TASK_RELEVANT field, which is what makes the matched-pair claim auditable.
    """

    fields: list[SemanticField] = field(default_factory=list)

    def task_relevant(self) -> list[SemanticField]:
        return [f for f in self.fields if f.role is FieldRole.TASK_RELEVANT]

    def by_canonical_order(self) -> list[SemanticField]:
        return sorted(self.fields, key=lambda f: f.schema_order)


# --------------------------------------------------------------------------
# Trajectory
# --------------------------------------------------------------------------


@dataclass
class Step:
    """One assistant turn that issues a tool call, plus that call's return."""

    assistant_text: str
    tool_name: str
    tool_args: dict[str, Any]
    returns: SemanticReturn
    is_decision_point: bool = False


@dataclass
class DecisionPoint:
    """Pre-registered per §6.1, before any data is inspected.

    Both branches must be legitimate; this is the behavioral arm's only
    measurement site, and fixing it in the spec is what keeps RQ2 honest.
    """

    kind: Literal["verify_then_act", "permission_check", "procedural_shortcut", "escalate_vs_resolve"]
    description: str
    cautious_branch: str          # tool name or observable behavior counted as cautious
    efficient_branch: str         # the legitimate alternative
    step_index: int               # which Step in the trajectory it sits at


@dataclass
class TaskSpec:
    task_id: str
    domain: str
    system_prompt: str
    user_task: str
    tools: list[ToolSchema]
    steps: list[Step]
    decision_point: DecisionPoint
    f3_site: int = 0              # step at which F3 inserts its transient failure
    solution_terms: list[str] = field(default_factory=list)  # for the §8.3 answer-leakage audit
    notes: str = ""

    def validate(self) -> list[str]:
        """Structural checks that must pass before the task enters generation."""
        errs: list[str] = []
        if not self.steps:
            errs.append(f"{self.task_id}: no steps")
        dp = self.decision_point
        if not (0 <= dp.step_index < len(self.steps)):
            errs.append(f"{self.task_id}: decision_point.step_index {dp.step_index} out of range")
        else:
            if not self.steps[dp.step_index].is_decision_point:
                errs.append(f"{self.task_id}: step {dp.step_index} not flagged is_decision_point")
        flagged = [i for i, s in enumerate(self.steps) if s.is_decision_point]
        if len(flagged) != 1:
            errs.append(f"{self.task_id}: expected exactly 1 decision point, found {len(flagged)}")
        tool_names = {t.name for t in self.tools}
        for i, s in enumerate(self.steps):
            if s.tool_name not in tool_names:
                errs.append(f"{self.task_id}: step {i} calls undeclared tool {s.tool_name!r}")
            if not s.returns.task_relevant():
                errs.append(f"{self.task_id}: step {i} has no task-relevant return field")
        # §7 harness verification found one conditional contamination route in
        # ADK: an instruction that interpolates session state via {placeholder}
        # templating picks up `__llm_request_key__`, written by the eval-only
        # _RequestIntercepterPlugin, from turn 2 onward. Static prompts are immune,
        # so require them. See results/harness_verification_sensitivity.json.
        if "{" in self.system_prompt or "}" in self.system_prompt:
            errs.append(f"{self.task_id}: system_prompt must not use state templating "
                        "({{...}}); it would expose eval-only harness state (§7)")
        if not (0 <= self.f3_site < len(self.steps)):
            errs.append(f"{self.task_id}: f3_site {self.f3_site} out of range")
        # Solution terms must be drawn from TASK_RELEVANT content. Contextual and
        # metadata fields are dropped by F1's eval-like arm by design, so a term
        # sourced from one appears in some arms and not others and trips the §8.3
        # answer-leakage audit -- an authoring trap, not a real leak.
        relevant = []
        for st in self.steps:
            relevant.extend(str(k) for k in st.tool_args)
            relevant.extend(str(v) for v in st.tool_args.values())
            for f in st.returns.task_relevant():
                relevant.append(f.name)
                relevant.append(str(f.value))
        hay = " ".join(relevant)
        for term in self.solution_terms:
            if term not in hay:
                errs.append(f"{self.task_id}: solution term {term!r} is not in any "
                            "task-relevant field or tool argument; F1's eval arm drops "
                            "contextual/metadata fields, so such a term breaks §8.3")
        for br in (dp.cautious_branch, dp.efficient_branch):
            if br not in tool_names:
                errs.append(f"{self.task_id}: decision branch {br!r} is not a declared tool")
        return errs

    def to_dict(self) -> dict:
        return asdict(self)
